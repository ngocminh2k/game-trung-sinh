const NODES: readonly SkillNode[] = SEEDS.map((seed) => ({ ...seed }))

const ALL_IDS = NODES.map((node) => node.id)
const UNIQUE = new Set(ALL_IDS)
if (UNIQUE.size !== ALL_IDS.length) throw new Error('skill-tree: duplicate node id')

const TIER_BY_BRANCH: Readonly<Record<typeof branches[number], ReadonlyArray<SkillNode>>> = (() => {
  const map: Record<string, SkillNode[]> = {}
  for (const branch of branches) map[branch] = []
  for (const node of NODES) {
    const list = map[node.branch]
    if (list === undefined) throw new Error(`skill-tree: unknown branch ${node.branch}`)
    list.push(node)
  }
  for (const branch of branches) {
    const list = map[branch]!
    list.sort((a, b) => a.tier - b.tier)
  }
  return map as Record<typeof branches[number], ReadonlyArray<SkillNode>>
})()

for (const branch of branches) {
  const list = TIER_BY_BRANCH[branch]!
  if (list.length !== 20) throw new Error(`skill-tree: ${branch} must have 20 tiers, has ${list.length}`)
  for (let i = 0; i < 20; i++) {
    const expected = i + 1
    const node = list[i]
    if (node === undefined) throw new Error(`skill-tree: ${branch} missing tier ${String(expected)}`)
    if (node.tier !== expected) {
      throw new Error(`skill-tree: ${branch} tier index ${String(i)} expected ${String(expected)}, got ${String(node.tier)}`)
    }
  }
}

if (NODES.length !== 100) throw new Error(`skill-tree: expected 100 nodes, got ${String(NODES.length)}`)

export const SKILL_TREES: Readonly<Record<typeof branches[number], ReadonlyArray<SkillNode>>> = TIER_BY_BRANCH
export const SKILL_NODES: readonly SkillNode[] = NODES
export const SKILL_BRANCHES = branches

export function getSkillNode(id: string): SkillNode | undefined {
  return NODES.find((node) => node.id === id)
}

export function skillNodesInBranch(branch: typeof branches[number]): ReadonlyArray<SkillNode> {
  return TIER_BY_BRANCH[branch] ?? []
}
