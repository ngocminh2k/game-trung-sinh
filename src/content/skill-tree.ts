// 5 branches × 20 tiers = 100 nodes. Each branch opens at tier 1 with stage
// requirement 0; later tiers gate on the stage, a level threshold, or a
// previously-known technique. Costs in `cost.skillPoints` are calibrated so a
// 5-stage run can afford roughly one branch's worth of unlocks; optional gold
// and item requirements give the higher tiers real world gates without
// inventing new currencies.
//
// Effects use the union from SkillNode.effect.kind. Numeric `value` is the
// flat bonus the node contributes; kind-specific fields (aoeRadius, status,
// stack, etc.) live alongside `value` as additional `key: number | string`
// pairs so the reducer can read whichever it needs.
//
// `conflictsWith` is symmetric by construction: if A conflicts with B then B
// conflicts with A. Conflicts only mark an effect theme, not a numeric cap —
// picking both is rejected with `ITEM_UNAVAILABLE` rather than halved.

